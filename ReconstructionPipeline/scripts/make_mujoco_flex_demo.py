"""
Assemble the MuJoCo flex demonstration (DEC-053, demo only) from the raw frames written by
`scripts/demo_mujoco_flex_slicer.sh`:

    ./.venv/bin/python -m ReconstructionPipeline.scripts.make_mujoco_flex_demo --raw <out>/raw --out <out>

Writes <out>/mujoco_flex_tissue.gif (offscreen MuJoCo renders of the flex), <out>/mujoco_flex_slicer.gif (Slicer
main window), <out>/mujoco_flex_contact_sheet.png and <out>/README.md. Every caption number is read from the CSV
written next to the frames (the flex worker's contact force and probe depth; the telemetry Slicer received), never
typed by hand.
"""

from __future__ import annotations

import argparse
import csv
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFont

FONT = None


def _font(size=16):
    for path in ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/TTF/DejaVuSans.ttf"):
        if os.path.exists(path):
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def _caption(img: Image.Image, lines, width=None) -> Image.Image:
    if width:
        img = img.resize((width, int(img.height * width / img.width)), Image.LANCZOS)
    font = _font(16)
    pad = 6 + 22 * len(lines)
    out = Image.new("RGB", (img.width, img.height + pad), (16, 18, 24))
    out.paste(img.convert("RGB"), (0, 0))
    d = ImageDraw.Draw(out)
    for i, line in enumerate(lines):
        d.text((8, img.height + 4 + 22 * i), line, fill=(235, 235, 235), font=font)
    return out


def _rows(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def _fmt(v, spec):
    try:
        return format(float(v), spec)
    except (TypeError, ValueError):
        return "n/a"


def flex_frames(raw):
    rows = _rows(os.path.join(raw, "flex", "flex_frames.csv"))
    frames = []
    for r in rows:
        p = os.path.join(raw, "flex", r["file"])
        if os.path.exists(p):
            frames.append(_caption(Image.open(p), [
                f"MuJoCo 4 flex (live, own process) | t = {_fmt(r['sim_time_s'], '.1f')} s sim",
                f"probe force {_fmt(r['force_along_minus_beam_n'], '.2f')} N | face depth below skin point "
                f"{_fmt(r['probe_face_depth_mm'], '.1f')} mm | max |u| {_fmt(r['max_displacement_mm'], '.1f')} mm"],
                width=560))
    return frames, rows


def slicer_frames(raw):
    rows = _rows(os.path.join(raw, "slicer", "snapshots.csv"))
    frames = []
    for r in rows:
        p = os.path.join(raw, "slicer", r["file"])
        if os.path.exists(p):
            frames.append(_caption(Image.open(p), [
                f"3D Slicer via OpenIGTLink | t = {_fmt(r['elapsed_s'], '.0f')} s | DeformedSkin from the MuJoCo flex",
                f"telemetry: force {_fmt(r['normal_force_n'], '.2f')} N, indentation "
                f"{_fmt(r['indentation_mm'], '.1f')} mm, in contact {r['in_contact']}"], width=960))
    return frames, rows


def save_gif(frames, path, ms):
    if frames:
        frames[0].save(path, save_all=True, append_images=frames[1:], duration=ms, loop=0, optimize=True)
        print(f"wrote {path} ({len(frames)} frames)")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    ff, frows = flex_frames(args.raw)
    sf, srows = slicer_frames(args.raw)
    save_gif(ff, os.path.join(args.out, "mujoco_flex_tissue.gif"), 120)
    save_gif(sf, os.path.join(args.out, "mujoco_flex_slicer.gif"), 600)
    # contact sheet: the flex frame with the largest force, and the Slicer frame received closest after it
    if ff and sf:
        forces = [float(r["force_along_minus_beam_n"]) for r in frows]
        fi = int(np.argmax(forces))
        contact = [i for i, r in enumerate(srows) if str(r.get("in_contact")) == "True"]
        si = contact[len(contact) // 2] if contact else len(sf) // 2
        a, b = ff[fi], sf[si].resize((int(sf[si].width * ff[fi].height / sf[si].height), ff[fi].height))
        sheet = Image.new("RGB", (a.width + b.width + 8, a.height), (16, 18, 24))
        sheet.paste(a, (0, 0))
        sheet.paste(b, (a.width + 8, 0))
        sheet.save(os.path.join(args.out, "mujoco_flex_contact_sheet.png"))
    f_vals = [float(r["force_along_minus_beam_n"]) for r in frows] or [float("nan")]
    d_vals = [float(r["probe_face_depth_mm"]) for r in frows] or [float("nan")]
    readme = f"""# MuJoCo flex soft-tissue demonstration (DEC-053, DEMO ONLY)

Generated by `scripts/demo_mujoco_flex_slicer.sh` → `ReconstructionPipeline/scripts/make_mujoco_flex_demo.py`.

- `mujoco_flex_tissue.gif`: offscreen MuJoCo 4 renders of the live flex tissue (patient tet mesh, Stable
  Neo-Hookean, fat/muscle moduli from the CT) and the probe body pressing into it. {len(ff)} frames.
- `mujoco_flex_slicer.gif`: 3D Slicer receiving the same deformation as `DeformedSkin` over OpenIGTLink, with the
  B-mode warped by the flex displacement field. {len(sf)} frames.
- `mujoco_flex_contact_sheet.png`: the flex frame with the largest probe force beside a Slicer frame in contact.

From `raw/flex/flex_frames.csv`: probe force {np.nanmin(f_vals):.2f}–{np.nanmax(f_vals):.2f} N, probe-face depth
below the commanded skin point {np.nanmin(d_vals):.1f}–{np.nanmax(d_vals):.1f} mm.

This is a demonstration of the pipeline, not a validated tissue model: the flex backend did not become a tissue
backend for any metric (see the DEC-053 gate result in DECISIONS.md and `results/mujoco_flex_fidelity_*`).
"""
    open(os.path.join(args.out, "README.md"), "w").write(readme)
    print("wrote", os.path.join(args.out, "README.md"))


if __name__ == "__main__":
    main()
